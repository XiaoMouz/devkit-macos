#!/usr/bin/env python3
"""Rebuild the explicit registry after adding/removing a module; no runtime scanning."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
files = sorted((root / 'Sources/DevKitCore/Tools').glob('*/*Tool.swift'))
types = [re.search(r'public enum (\w+): ToolModule', p.read_text()).group(1) for p in files]
target = root / 'Sources/DevKitCore/Registry/ToolRegistry.swift'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text('''// Generated by Scripts/update-registry.py. Tool implementations remain in their feature directories.
import Foundation

public enum ToolRegistry {
    public static let all: [any ToolModule.Type] = [
''' + ''.join('        ' + t + '.self,\n' for t in types) + '''    ]
    public static func find(_ id: String) -> (any ToolModule.Type)? {
        all.first { $0.metadata.id == id }
    }
}
''')
print(f'Registered {len(types)} modules')
